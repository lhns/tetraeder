"""Stage names that scripts/exit_run.sh knows, against every list handed to it.

A misspelled stage in STAGES / B1_STAGES is silently skipped on the box (or opts into nothing), and the box bills the
whole time. Lists checked: the default lists in scripts/session.sh, `B1_STAGES=` / `STAGES=` / `stage order:` lines of
the committed session logs, and the env var STAGES (the one to use before provisioning):

    STAGES="smoke disk-curve main-prefetch" pytest tests/test_stage_names.py
"""

from __future__ import annotations

import os
import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
EXIT_RUN = (ROOT / "scripts" / "exit_run.sh").read_text(encoding="utf-8")
NAME = r"[a-z][a-z0-9-]*"


def _strip_comments(src: str) -> str:
    return "\n".join(re.sub(r"(^|\s)#.*$", "", ln) for ln in src.splitlines())


def known_stages(src: str = EXIT_RUN) -> set[str]:
    """Every stage name exit_run.sh can react to, found from its source."""
    code = _strip_comments(src)
    names: set[str] = set()
    # want "name", exit_regime name <minutes>, baseline <bin> name <minutes>, and opt-in tests on " $STAGES "
    names |= set(re.findall(rf'\bwant\s+"?({NAME})"?(?=\s|;|$|\|)', code))
    names |= set(re.findall(rf'\bexit_regime\s+"?({NAME})"?\s+\d', code))
    names |= set(re.findall(rf'\bbaseline\s+\S+\s+"?({NAME})"?\s+\d', code))
    names |= set(re.findall(rf'\*" ({NAME}) "\*', code))
    # functions that do `want "$name"` with a literal name (levers_snap, ...)
    names |= set(re.findall(rf"\bname=({NAME})(?=\s|$)", code, re.M))
    # function families: stage = <fn>[-<arg>]; the arg is a literal at a call, or a loop variable
    for fn, prefix in (("ktransformers", "ktransformers"), ("llamacpp_cache", "llamacpp-cache"), ("colibri", "colibri")):
        if fn != "colibri":  # colibri has no bare stage
            names.add(prefix)
        for arg in re.findall(rf"^\s*{fn}\s+([a-z][a-z0-9-]*)\s*$", code, re.M):
            names.add(f"{prefix}-{arg}")
        for lst in re.findall(rf"for _v in ([^;\n]+); do\n(?:(?!\s*done\b).*\n)*?.*{prefix}-\$_v", code):
            names |= {f"{prefix}-{v}" for v in lst.split()}
    # a harness run that VARIANTS adds ("name:ENV=..." words)
    names |= {v.split(":")[0] for v in os.environ.get("VARIANTS", "").split() if v}
    return names


def lists_in_text(text: str) -> list[tuple[str, list[str]]]:
    """(where, names) for each stage list written as B1_STAGES=..., STAGES=... or `stage order: ...`."""
    out = []
    for m in re.finditer(r"""\b(?:B1_STAGES|B2_STAGES|STAGES|stages)=(?:"([^"\n]*)"|'([^'\n]*)'|(\S+))""", text):
        val = m.group(1) or m.group(2) or m.group(3) or ""
        if "$" not in val:  # "$stages $more" is composed, its parts are checked where they are set
            out.append((m.group(0)[:60], val.split()))
    for m in re.finditer(r"stage order:(.*)", text):
        out.append((m.group(0)[:60], m.group(1).split()))
    return out


def unknown(names: list[str], known: set[str]) -> list[str]:
    # ledger-<id> stages are generated by anchors-builder-short
    return [n for n in names if n not in known and not n.startswith("ledger-")]


KNOWN = known_stages()


def test_extraction_finds_the_core_stages() -> None:
    # a regex that silently found nothing would make every check below pass
    for must in ("smoke", "disk-curve", "main-prefetch", "kv-q8", "main-overlap", "trace", "ktransformers",
                 "ktransformers-avx2", "ktransformers-avx512-repeat", "llamacpp-cache", "llamacpp-cache-dio",
                 "llamacpp-cache-dio-repeat", "llamacpp-cache-poll0", "colibri-short", "colibri-deep",
                 "anchors-builder-short", "main-overlap-poll0-thp-repeat", "levers-snap", "moe-tune", "llama-fit",
                 "dispatch-floor", "gpu-tests", "kv-quality", "reference", "exit-ik-ot-fit-d32k"):
        assert must in KNOWN, f"{must} not extracted from exit_run.sh: fix known_stages()"
    assert len(KNOWN) > 60


def test_a_typo_is_unknown() -> None:
    assert unknown(["main-prefecth", "smoke"], KNOWN) == ["main-prefecth"]


def test_session_defaults_are_known() -> None:
    src = (ROOT / "scripts" / "session.sh").read_text(encoding="utf-8")
    bad = {where: unknown(names, KNOWN) for where, names in lists_in_text(src)}
    assert not {k: v for k, v in bad.items() if v}, bad


@pytest.mark.parametrize("log", sorted((ROOT / "bench" / "results").glob("*/session-*.log")), ids=lambda p: p.parent.name + "/" + p.name)
def test_committed_session_logs(log: Path) -> None:
    bad = [(w, u) for w, names in lists_in_text(log.read_text(encoding="utf-8", errors="replace")) if (u := unknown(names, KNOWN))]
    assert not bad, f"{log.name} names stages exit_run.sh does not know: {bad}"


@pytest.mark.skipif(not os.environ.get("STAGES", "").strip(), reason="set STAGES to check a list before provisioning")
def test_env_stages() -> None:
    names = os.environ["STAGES"].split()
    assert not unknown(names, KNOWN), f"unknown stages {unknown(names, KNOWN)}; known: {sorted(KNOWN)}"
